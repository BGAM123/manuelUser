type Key = keyof (typeof dict)["fr"];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string };
const I18nContext = createContext<Ctx>({
  lang: "fr",
  setLang: () => {},
  t: (k) => dict.fr[k] ?? k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("minepia.lang") as Lang | null;
      if (saved === "en" || saved === "fr") setLangState(saved);
    } catch {}
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("minepia.lang", l);
    } catch {}
  };
  const t = (k: Key) => dict[lang][k] ?? dict.fr[k] ?? k;
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
export function useT() {
  return useContext(I18nContext).t;
}